#!/usr/bin/env python3
"""
VERITAS VIOLATION GUARDS v1.0 (30.09.2026)

Контекстні фільтри для двох формальних LAC-порушень, які давали хибні
спрацьовування на звичайній аналітичній публіцистиці й через це
вимикали академічний щит (щит вимикається будь-яким порушенням
із severity > 0.5):

  1. ANONYMOUS_AUTHORITY (0.6)
     Голі дієслова «вважають» / «вважається» / «кажуть» / «говорять»
     ловили нейтральні речення на кшталт «що люди вважають відомим»
     і «що вважається допустимою інформацією». Анонімне посилання на
     авторитет — це конструкція-атрибуція («вважають, що ...»), а не
     саме дієслово. Крім того, «кажуть» без меж слова збігалося всередині
     «покажуть», «скажуть», «розкажуть».

  2. DOMAIN_COLLAPSE physics+politics / physics+business (0.6)
     Слово «ентропія» було єдиним тригером домену physics. В
     інформаційному, епістемічному, ML-контексті це штатний термін, а не
     заява про фізику, тож будь-яка стаття з «ентропією» і одним словом
     «політика» отримувала «порушення кордону доменів».

Модуль чисто функціональний, без стану й залежностей. Ядро підключає його
через try/except; якщо модуля немає, діє стара поведінка.
"""

import re
from typing import Iterable, Optional

# ---------------------------------------------------------------------
# 1. ANONYMOUS AUTHORITY
# ---------------------------------------------------------------------
# ключ: оригінальний патерн із ядра (як є), значення: вужча форма.
# Інші патерни ядра (журналістські анонімні джерела, «дехто каже»,
# «поширена думка» тощо) не чіпаємо, вони вже достатньо специфічні.
_NARROWED_ANON_PATTERNS = {
    r'кажуть': r'\bкажуть\b',
    r'говорять': r'\bговорять\b',
    r'вважають': r'\bвважають,?\s+що\b',
    r'вважається': r'\bвважається,?\s+що\b',
}


def find_anonymous_authority(text_lower: str, patterns: Iterable[str]) -> Optional[str]:
    """
    Повертає перший патерн (у вигляді оригінального рядка з ядра), що
    справді означає анонімне посилання на авторитет, або None.

    text_lower: текст, уже приведений до нижнього регістру.
    patterns:   self.ANONYMOUS_AUTHORITY_PATTERNS з ядра.
    """
    for original in patterns:
        effective = _NARROWED_ANON_PATTERNS.get(original, original)
        if re.search(effective, text_lower):
            return original
    return None


# ---------------------------------------------------------------------
# 2. DOMAIN METAPHORS
# ---------------------------------------------------------------------
# «ентропія» як слово не доводить, що текст говорить про фізику:
# в інформатиці, епістемології, теорії систем це штатний термін.
# Домен physics тригериться лише «жорсткими» термінами (термодинаміка,
# квантовий, фізика, закон фізики, формула, рівняння, математика).
_ENTROPY_WORD = re.compile(r'\bентропі\w*')


def neutralize_domain_metaphors(domain: str, text_lower: str) -> str:
    """
    Повертає текст, з якого прибрано слова, що не мають вважатися
    доказом приналежності до домену. Використовується ЛИШЕ для
    визначення наявності домену, не для подальшого аналізу.
    """
    if domain == 'physics':
        return _ENTROPY_WORD.sub(' ', text_lower)
    return text_lower
